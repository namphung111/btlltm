CREATE TABLE IF NOT EXISTS users (
    username VARCHAR(64) PRIMARY KEY,
    password_hash VARCHAR(100) NOT NULL,
    created_at BIGINT NOT NULL
);

ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar_file VARCHAR(80);
ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar_content_type VARCHAR(100);
ALTER TABLE users ADD COLUMN IF NOT EXISTS display_name VARCHAR(100);
UPDATE users SET display_name = username WHERE display_name IS NULL;

CREATE TABLE IF NOT EXISTS rooms (
    room_id VARCHAR(36) PRIMARY KEY,
    room_name VARCHAR(100) NOT NULL,
    created_by VARCHAR(64) NOT NULL REFERENCES users(username) ON DELETE RESTRICT,
    created_at BIGINT NOT NULL,
    deleted_at BIGINT
);

ALTER TABLE rooms ADD COLUMN IF NOT EXISTS deleted_at BIGINT;

CREATE TABLE IF NOT EXISTS room_members (
    room_id VARCHAR(36) NOT NULL REFERENCES rooms(room_id) ON DELETE CASCADE,
    username VARCHAR(64) NOT NULL REFERENCES users(username) ON DELETE CASCADE,
    joined_at BIGINT NOT NULL,
    role VARCHAR(16) NOT NULL DEFAULT 'MEMBER',
    left_at BIGINT,
    PRIMARY KEY (room_id, username)
);

ALTER TABLE room_members ADD COLUMN IF NOT EXISTS role VARCHAR(16) NOT NULL DEFAULT 'MEMBER';
ALTER TABLE room_members ADD COLUMN IF NOT EXISTS left_at BIGINT;
UPDATE room_members SET role = 'LEADER'
WHERE username IN (SELECT created_by FROM rooms WHERE rooms.room_id = room_members.room_id);

CREATE TABLE IF NOT EXISTS chat_files (
    file_id VARCHAR(36) PRIMARY KEY,
    room_id VARCHAR(36) NOT NULL REFERENCES rooms(room_id) ON DELETE CASCADE,
    uploaded_by VARCHAR(64) NOT NULL REFERENCES users(username) ON DELETE RESTRICT,
    original_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(150) NOT NULL,
    storage_name VARCHAR(80) NOT NULL,
    created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS messages (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id VARCHAR(36) NOT NULL REFERENCES rooms(room_id) ON DELETE CASCADE,
    sender_username VARCHAR(64) NOT NULL REFERENCES users(username) ON DELETE RESTRICT,
    content TEXT NOT NULL,
    file_id VARCHAR(36) REFERENCES chat_files(file_id) ON DELETE SET NULL,
    created_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_messages_room_id ON messages(room_id, message_id);
CREATE INDEX IF NOT EXISTS idx_room_members_username ON room_members(username, left_at);

CREATE TABLE IF NOT EXISTS message_read_receipts (
    message_id BIGINT NOT NULL REFERENCES messages(message_id) ON DELETE CASCADE,
    username VARCHAR(64) NOT NULL REFERENCES users(username) ON DELETE CASCADE,
    read_at BIGINT NOT NULL,
    PRIMARY KEY (message_id, username)
);

CREATE TABLE IF NOT EXISTS direct_conversations (
    conversation_id VARCHAR(36) PRIMARY KEY,
    participant_a VARCHAR(64) NOT NULL REFERENCES users(username) ON DELETE CASCADE,
    participant_b VARCHAR(64) NOT NULL REFERENCES users(username) ON DELETE CASCADE,
    created_at BIGINT NOT NULL,
    last_message_at BIGINT NOT NULL,
    UNIQUE (participant_a, participant_b),
    CHECK (participant_a <> participant_b)
);

CREATE TABLE IF NOT EXISTS direct_messages (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id VARCHAR(36) NOT NULL
        REFERENCES direct_conversations(conversation_id) ON DELETE CASCADE,
    sender_username VARCHAR(64) NOT NULL REFERENCES users(username) ON DELETE RESTRICT,
    content TEXT NOT NULL,
    created_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_direct_messages_conversation
    ON direct_messages(conversation_id, message_id);

CREATE TABLE IF NOT EXISTS direct_message_read_receipts (
    message_id BIGINT NOT NULL REFERENCES direct_messages(message_id) ON DELETE CASCADE,
    username VARCHAR(64) NOT NULL REFERENCES users(username) ON DELETE CASCADE,
    read_at BIGINT NOT NULL,
    PRIMARY KEY (message_id, username)
);
